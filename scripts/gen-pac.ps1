<#
.SYNOPSIS
    Generate a PAC file for system-proxy based split tunnelling.

.DESCRIPTION
    Two modes:

      minimal     A single line. The local proxy core's rule set (GEOSITE / GEOIP)
                  decides what goes where; the PAC only hands traffic to it.
                  Use this once the old client has been retired.

      transition  Multi-tier fallback: new core -> old client -> direct for domains
                  that should go through the tunnel, and new core -> direct for
                  everything else. Use this while both clients are running, so a
                  dead new core does not take every site down with it.

    The script never writes the registry. Switching is a separate, one-line action
    (documented in docs/deploy.md) so it stays trivially reversible.

.PARAMETER Mode
    minimal or transition. Default transition (the safe one during a migration).

.PARAMETER HttpPort
    New proxy core's HTTP port. Default 7890.

.PARAMETER LegacyPort
    Old client's HTTP port, used only in transition mode. Default 10809.

.PARAMETER OutputPath
    Where to write the file. Default <repo>/proxy.pac.

.PARAMETER DomainListPath
    Optional text file, one domain per line (# for comments). Those domains are
    emitted as an explicit list in transition mode. Without it, only the built-in
    suffix rules (.cn / .gov.cn / ...) are used.

.EXAMPLE
    .\gen-pac.ps1 -Mode transition -DomainListPath .\my-domains.txt

.EXAMPLE
    .\gen-pac.ps1 -Mode minimal -HttpPort 7890
#>

[CmdletBinding()]
param(
    [ValidateSet('minimal', 'transition')]
    [string]$Mode = 'transition',

    [int]$HttpPort = 7890,
    [int]$LegacyPort = 10809,
    [string]$OutputPath,
    [string]$DomainListPath
)

$ErrorActionPreference = 'Continue'

$root = Split-Path -Parent $PSScriptRoot
if (-not $OutputPath) {
    $OutputPath = Join-Path $root 'proxy.pac'
}
$OutputPath = [System.IO.Path]::GetFullPath($OutputPath)

Write-Host ""
Write-Host "=== PAC generator ===" -ForegroundColor Cyan
Write-Host "  Mode      : $Mode"
Write-Host "  HTTP port : $HttpPort"
if ($Mode -eq 'transition') {
    Write-Host "  Legacy    : $LegacyPort"
}
Write-Host "  Output    : $OutputPath"
Write-Host ""

# ---------- read the optional domain list ----------
$domains = @()
if ($DomainListPath) {
    if (-not (Test-Path $DomainListPath)) {
        Write-Host "  [X] domain list not found: $DomainListPath" -ForegroundColor Red
        exit 1
    }
    $domains = Get-Content $DomainListPath |
        ForEach-Object { $_.Trim() } |
        Where-Object { $_ -and -not $_.StartsWith('#') } |
        ForEach-Object { $_.TrimStart('.').ToLower() } |
        Select-Object -Unique
    Write-Host "  [OK] $($domains.Count) domains loaded from $(Split-Path $DomainListPath -Leaf)"
}
else {
    Write-Host "  [i] no -DomainListPath given; only built-in suffix rules will be emitted" -ForegroundColor DarkGray
}

# ---------- build ----------
if ($Mode -eq 'minimal') {
    # One line. The proxy core's rule set does the splitting.
    # The trailing DIRECT keeps the browser online if the core is not running.
    $pac = @'
// Generated by gen-pac.ps1 (minimal mode)
//
// The local proxy core decides what goes through the tunnel; this file only
// hands traffic to it. DIRECT at the end is a safety net: if the core is not
// listening, the browser falls back to a direct connection instead of showing
// "no internet".
//
// Browsers try each entry in order, and a refused local port fails instantly,
// so the fallback costs no visible delay.

function FindProxyForURL(url, host) {
    if (isPlainHostName(host) ||
        shExpMatch(host, "127.*") ||
        shExpMatch(host, "localhost") ||
        shExpMatch(host, "*.local")) {
        return "DIRECT";
    }
    return "PROXY 127.0.0.1:{{HTTP}}; DIRECT";
}
'@
}
else {
    # Transition: keep explicit domain rules, add multi-tier fallback.
    $domainLines = ''
    if ($domains.Count -gt 0) {
        $pairs = $domains | ForEach-Object { '        "' + $_ + '"' }
        $domainLines = $pairs -join ",`r`n"
    }
    else {
        $domainLines = '        // (empty - add domains via -DomainListPath)'
    }

    $pac = @"
// Generated by gen-pac.ps1 (transition mode)
//
// While BOTH the new core and the old client are running, this file routes
//   domain rules hit  ->  new core, then old client, then direct
//   everything else   ->  new core, then direct
//
// The non-domain branch deliberately does NOT fall back to the old client:
// doing so would push foreign sites into the tunnel.
//
// Browsers only fall back when the proxy PORT refuses the connection. If the
// core process is alive but its tunnel is broken, no fallback happens -- that
// case needs observation and a manual rollback (see docs/deploy.md).

function FindProxyForURL(url, host) {
    if (isPlainHostName(host) ||
        shExpMatch(host, "127.*") ||
        shExpMatch(host, "localhost") ||
        shExpMatch(host, "*.local")) {
        return "DIRECT";
    }

    var TIER_CN    = "PROXY 127.0.0.1:$HttpPort; PROXY 127.0.0.1:$LegacyPort; DIRECT";
    var TIER_OTHER = "PROXY 127.0.0.1:$HttpPort; DIRECT";

    // -- 1. country-code suffixes --
    var suffixes = [".cn", ".gov.cn", ".com.cn", ".net.cn", ".org.cn", ".edu.cn"];
    for (var i = 0; i < suffixes.length; i++) {
        if (dnsDomainIs(host, suffixes[i])) return TIER_CN;
    }

    // -- 2. explicit domains --
    var list = [
$domainLines
    ];
    for (var j = 0; j < list.length; j++) {
        if (dnsDomainIs(host, list[j]) || host === list[j]) return TIER_CN;
    }

    // -- 3. everything else --
    return TIER_OTHER;
}
"@
}

$pac = $pac.Replace('{{HTTP}}', $HttpPort.ToString())

# ---------- sanity check the JS before writing ----------
# Catch unbalanced braces early: a malformed PAC silently disables the proxy.
$open  = ([regex]::Matches($pac, '\{')).Count
$close = ([regex]::Matches($pac, '\}')).Count
if ($open -ne $close) {
    Write-Host "  [X] generated PAC has unbalanced braces ($open vs $close) - refusing to write" -ForegroundColor Red
    exit 1
}
if ($pac -notmatch 'function FindProxyForURL') {
    Write-Host "  [X] generated PAC has no FindProxyForURL - refusing to write" -ForegroundColor Red
    exit 1
}

# ---------- write ----------
$dir = Split-Path $OutputPath -Parent
if (-not (Test-Path $dir)) {
    New-Item -ItemType Directory -Path $dir -Force | Out-Null
}

# Back up any existing file: a PAC typo takes the browser offline, and the old
# copy is the fastest way back.
if (Test-Path $OutputPath) {
    $backup = "$OutputPath.bak-$(Get-Date -Format 'yyyyMMdd-HHmmss')"
    Copy-Item $OutputPath $backup -Force
    Write-Host "  [i] existing file backed up: $(Split-Path $backup -Leaf)" -ForegroundColor DarkGray
}

# No BOM. Browsers read PAC as text; a BOM at the start of a JS file can break
# the first token.
[System.IO.File]::WriteAllText($OutputPath, $pac, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "  [OK] written: $OutputPath  ($((Get-Item $OutputPath).Length) bytes)"

# ---------- summary ----------
$fileUrl = 'file:///' + ($OutputPath -replace '\\', '/')

Write-Host ""
Write-Host "=== done ===" -ForegroundColor Green
Write-Host "  mode      : $Mode"
if ($Mode -eq 'transition') {
    Write-Host "  domain rules : $($domains.Count)"
    Write-Host "  fallback  : new($HttpPort) -> old($LegacyPort) -> direct"
}
else {
    Write-Host "  fallback  : new($HttpPort) -> direct"
}
Write-Host ""
Write-Host "  File URL for the AutoConfigURL registry value:" -ForegroundColor DarkGray
Write-Host "    $fileUrl" -ForegroundColor DarkGray
Write-Host ""
Write-Host "  To activate (writes to HKCU, current user only):" -ForegroundColor DarkGray
Write-Host "    Set-ItemProperty 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Internet Settings' ``" -ForegroundColor DarkGray
Write-Host "      -Name AutoConfigURL -Value '$fileUrl' -Force" -ForegroundColor DarkGray
Write-Host ""
Write-Host "  To roll back, point AutoConfigURL at the previous PAC path." -ForegroundColor DarkGray
Write-Host "  Always change the FILE NAME or the registry value, never edit a PAC in place:" -ForegroundColor DarkGray
Write-Host "  browsers cache it and may keep using the old script for hours." -ForegroundColor DarkGray
