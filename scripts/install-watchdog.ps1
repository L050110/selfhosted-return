<#
.SYNOPSIS
    Install a watchdog for hysteria2 or mihomo: restart automatically on crash.

.DESCRIPTION
    Does three things:
      1. Generates a loop script (restart after N seconds on exit)
      2. Registers a scheduled task (normal privileges, every 5 min, ignore-if-running)
      3. Starts it and verifies, including a real crash-recovery test

    Why not rely on "start at login" alone:
      start-at-login does NOT mean restart-on-crash.

    Why not "scheduled task + Highest + Interactive":
      That combination fails silently on Windows (LastTaskResult=1).

    Why the task repeats every 5 minutes:
      The watchdog itself can hang. Repeat + IgnoreNew covers that.

.PARAMETER Role
    server or client.

.PARAMETER WorkDir
    Working directory. Default: parent of this script's folder (repo root).

.PARAMETER ExeName
    Executable name. Default hysteria.exe. Use mihomo.exe for mihomo.

.PARAMETER RestartDelay
    Seconds to wait before restarting. Default 5.

.PARAMETER TaskName
    Scheduled task name. Default hysteria-<role>-watchdog.

.EXAMPLE
    .\install-watchdog.ps1 -Role server

.EXAMPLE
    .\install-watchdog.ps1 -Role client -ExeName mihomo.exe
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [ValidateSet('server', 'client')]
    [string]$Role,

    [string]$WorkDir,
    [string]$ExeName = 'hysteria.exe',
    [int]$RestartDelay = 5,
    [string]$TaskName
)

$ErrorActionPreference = 'Stop'

if (-not $WorkDir) {
    $WorkDir = Split-Path -Parent $PSScriptRoot
}
$WorkDir = (Resolve-Path $WorkDir).Path

if (-not $TaskName) {
    $TaskName = "hysteria-$Role-watchdog"
}

$configName = if ($Role -eq 'server') { 'server.yaml' } else { 'client.yaml' }
$exePath    = Join-Path $WorkDir $ExeName
$cfgPath    = Join-Path $WorkDir $configName
$runScript  = Join-Path $WorkDir "run-$Role.ps1"
$logPath    = Join-Path $WorkDir "$Role-watchdog.log"
$stdoutPath = Join-Path $WorkDir "$Role-stdout.log"

Write-Host ""
Write-Host "=== Watchdog install ===" -ForegroundColor Cyan
Write-Host "  Role      : $Role"
Write-Host "  WorkDir   : $WorkDir"
Write-Host "  Exe       : $ExeName"
Write-Host "  Config    : $configName"
Write-Host "  Task      : $TaskName"
Write-Host ""

# ---------- preflight ----------
$fail = $false
if (-not (Test-Path $exePath)) {
    Write-Host "  [X] not found: $ExeName" -ForegroundColor Red
    $fail = $true
} else {
    Write-Host "  [OK] $ExeName  ($([math]::Round((Get-Item $exePath).Length / 1MB, 2)) MB)"
}

if (-not (Test-Path $cfgPath)) {
    Write-Host "  [X] not found: $configName" -ForegroundColor Red
    $fail = $true
} else {
    Write-Host "  [OK] $configName  ($((Get-Item $cfgPath).Length) bytes)"
}

if ($fail) {
    Write-Host ""
    Write-Host "Missing files. Run setup-$Role.ps1 first." -ForegroundColor Yellow
    exit 1
}

# ---------- 1. generate loop script ----------
# Template uses {{TOKENS}} and single-quoted here-string so nothing is expanded here.
# Critical: Set-Location is required, otherwise relative paths in the yaml
# (e.g. ./server.crt) resolve against the caller's cwd and the process exits at once.
$template = @'
# Auto-generated by install-watchdog.ps1. Do not edit by hand.
$dir = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $dir

$exe = Join-Path $dir '{{EXE}}'
$log = Join-Path $dir '{{ROLE}}-watchdog.log'
$out = Join-Path $dir '{{ROLE}}-stdout.log'

$argList = @({{ARGS}})

while ($true) {
    $ts = Get-Date -Format 's'
    & $exe @argList *>> $out
    $code = $LASTEXITCODE
    Add-Content $log "$ts exited code=$code"
    Start-Sleep -Seconds {{DELAY}}
}
'@

# Build the argument array literal depending on the executable.
if ($ExeName -match 'mihomo') {
    $argsLiteral = "'-d', `$dir"
} else {
    $argsLiteral = "'$Role', '-c', `$cfg"
}
$argsLiteral = "'$Role', '-c', (Join-Path `$dir '{{CONFIG}}')"
if ($ExeName -match 'mihomo') {
    $argsLiteral = "'-d', `$dir"
}

$runContent = $template.
    Replace('{{EXE}}', $ExeName).
    Replace('{{ROLE}}', $Role).
    Replace('{{CONFIG}}', $configName).
    Replace('{{ARGS}}', $argsLiteral).
    Replace('{{DELAY}}', $RestartDelay.ToString())

[System.IO.File]::WriteAllText($runScript, $runContent, (New-Object System.Text.UTF8Encoding($true)))
Write-Host "  [OK] loop script: run-$Role.ps1"

# ---------- 2. register scheduled task ----------
try { & schtasks /delete /tn $TaskName /f 2>&1 | Out-Null } catch { }

$action = New-ScheduledTaskAction `
    -Execute "conhost.exe" `
    -Argument "--headless powershell -NoProfile -ExecutionPolicy Bypass -File `"$runScript`"" `
    -WorkingDirectory $WorkDir

$atLogon = New-ScheduledTaskTrigger -AtLogOn -User "$env:USERDOMAIN\$env:USERNAME"
$repeat  = New-ScheduledTaskTrigger -Once -At (Get-Date) -RepetitionInterval (New-TimeSpan -Minutes 5)

$settings = New-ScheduledTaskSettingsSet `
    -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries `
    -ExecutionTimeLimit ([TimeSpan]::Zero) `
    -MultipleInstances IgnoreNew `
    -StartWhenAvailable `
    -RestartCount 3 `
    -RestartInterval (New-TimeSpan -Minutes 1)

$principal = New-ScheduledTaskPrincipal `
    -UserId "$env:USERDOMAIN\$env:USERNAME" `
    -LogonType Interactive `
    -RunLevel Limited

try {
    Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger @($atLogon, $repeat) `
        -Settings $settings -Principal $principal -Force -ErrorAction Stop | Out-Null
    Write-Host "  [OK] task registered (logon + every 5 min)"
}
catch {
    Write-Host "  [!] logon trigger rejected: $($_.Exception.Message)" -ForegroundColor Yellow
    try {
        Register-ScheduledTask -TaskName $TaskName -Action $action `
            -Trigger $repeat -Settings $settings -Principal $principal -Force | Out-Null
        Write-Host "  [OK] task registered (every 5 min only)"
    }
    catch {
        Write-Host "  [X] registration failed: $($_.Exception.Message)" -ForegroundColor Red
        exit 1
    }
}

# ---------- 3. start and verify ----------
Write-Host ""
Write-Host "=== Start and verify ===" -ForegroundColor Cyan

$procName = [System.IO.Path]::GetFileNameWithoutExtension($ExeName)
Get-Process $procName -ErrorAction SilentlyContinue | ForEach-Object {
    Write-Host "  stopping existing pid=$($_.Id)"
    Stop-Process -Id $_.Id -Force -ErrorAction SilentlyContinue
}
Start-Sleep -Seconds 2

Start-ScheduledTask -TaskName $TaskName
Write-Host "  waiting 15s for the watchdog to launch it..."
Start-Sleep -Seconds 15

$p = Get-Process $procName -ErrorAction SilentlyContinue
if (-not $p) {
    Write-Host "  [X] process did not start" -ForegroundColor Red
    if (Test-Path $logPath) {
        Write-Host "  --- last 5 lines of $Role-watchdog.log ---"
        Get-Content $logPath -Tail 5 | ForEach-Object { Write-Host "    $_" }
    }
    if (Test-Path $stdoutPath) {
        Write-Host "  --- last 5 lines of $Role-stdout.log ---"
        Get-Content $stdoutPath -Tail 5 | ForEach-Object { Write-Host "    $_" }
    }
    exit 1
}
Write-Host "  [OK] running: pid=$($p[0].Id) started $($p[0].StartTime.ToString('HH:mm:ss'))" -ForegroundColor Green

# ---------- 4. crash-recovery test ----------
Write-Host ""
Write-Host "=== Crash recovery test (will kill the process once) ===" -ForegroundColor Cyan
$oldPid = $p[0].Id
Write-Host "  killing pid=$oldPid"
Stop-Process -Id $oldPid -Force -ErrorAction SilentlyContinue

$waitSec = $RestartDelay + 10
Write-Host "  waiting ${waitSec}s..."
Start-Sleep -Seconds $waitSec

$p2 = Get-Process $procName -ErrorAction SilentlyContinue
if ($p2 -and $p2[0].Id -ne $oldPid) {
    Write-Host "  [OK] auto-recovered: new pid=$($p2[0].Id)" -ForegroundColor Green
}
elseif ($p2) {
    Write-Host "  [!] process present but pid unchanged; it may not have been killed" -ForegroundColor Yellow
}
else {
    Write-Host "  [X] did not recover" -ForegroundColor Red
    exit 1
}

# ---------- summary ----------
Write-Host ""
Write-Host "=== Done ===" -ForegroundColor Green
Write-Host "  Task    : $TaskName"
Write-Host "  State   : $((Get-ScheduledTask -TaskName $TaskName).State)"
Write-Host "  Log     : $logPath"
Write-Host ""
Write-Host "  To disable : schtasks /change /tn `"$TaskName`" /disable" -ForegroundColor DarkGray
Write-Host "  To remove  : schtasks /delete /tn `"$TaskName`" /f" -ForegroundColor DarkGray
